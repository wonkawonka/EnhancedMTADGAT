import argparse
import csv
import json
from pathlib import Path


def load_registry(registry_path):
    with open(registry_path, "r", encoding="utf-8") as f:
        return json.load(f)


def flatten_metrics(prefix, payload, row):
    for key, value in payload.items():
        next_key = f"{prefix}_{key}" if prefix else key
        if isinstance(value, dict):
            flatten_metrics(next_key, value, row)
        else:
            row[next_key] = value


def collect_case_rows(experiment):
    output_dir = Path(experiment["output_dir"])
    if not output_dir.exists():
        return [{
            "experiment_name": experiment["name"],
            "dataset": experiment["dataset"],
            "run_id": experiment["run_id"],
            "output_dir": str(output_dir),
            "case_path": "",
            "status": "missing_output_dir",
        }]

    summary_files = sorted(output_dir.rglob("summary_metrics.json"))
    if not summary_files:
        return [{
            "experiment_name": experiment["name"],
            "dataset": experiment["dataset"],
            "run_id": experiment["run_id"],
            "output_dir": str(output_dir),
            "case_path": "",
            "status": "missing_summary_metrics",
        }]

    case_rows = []
    for summary_file in summary_files:
        row = {
            "experiment_name": experiment["name"],
            "dataset": experiment["dataset"],
            "run_id": experiment["run_id"],
            "output_dir": str(output_dir),
            "case_path": str(summary_file.parent),
            "case_relpath": str(summary_file.parent.relative_to(output_dir)),
            "status": experiment.get("status", "unknown"),
        }

        row.update({
            f"arg_{key}": value
            for key, value in experiment.get("args", {}).items()
        })

        with open(summary_file, "r", encoding="utf-8") as f:
            summary_payload = json.load(f)
        flatten_metrics("", summary_payload, row)

        thresholds_file = summary_file.parent / "thresholds.json"
        if thresholds_file.exists():
            with open(thresholds_file, "r", encoding="utf-8") as f:
                thresholds_payload = json.load(f)
            flatten_metrics("threshold", thresholds_payload, row)

        case_rows.append(row)

    return case_rows


def write_csv(rows, csv_path):
    fieldnames = sorted({key for row in rows for key in row.keys()})
    with open(csv_path, "w", newline="", encoding="utf-8-sig") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for row in rows:
            writer.writerow(row)


def parse_args():
    parser = argparse.ArgumentParser(description="Collect comparison experiment results into a flat table.")
    parser.add_argument(
        "--registry",
        type=str,
        required=True,
        help="Path to run_registry.json generated by compare_experiments.py",
    )
    parser.add_argument(
        "--output-prefix",
        type=str,
        default="",
        help="Optional output prefix. Defaults to the registry directory / comparison_results",
    )
    return parser.parse_args()


def main():
    args = parse_args()
    registry_path = Path(args.registry).resolve()
    registry = load_registry(registry_path)

    all_rows = []
    for experiment in registry.get("experiments", []):
        all_rows.extend(collect_case_rows(experiment))

    if args.output_prefix:
        output_prefix = Path(args.output_prefix).resolve()
    else:
        output_prefix = registry_path.parent / "comparison_results"

    output_prefix.parent.mkdir(parents=True, exist_ok=True)
    csv_path = output_prefix.with_suffix(".csv")
    json_path = output_prefix.with_suffix(".json")

    write_csv(all_rows, csv_path)
    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(all_rows, f, indent=2, ensure_ascii=False)

    print(f"Collected {len(all_rows)} rows")
    print(f"CSV  : {csv_path}")
    print(f"JSON : {json_path}")


if __name__ == "__main__":
    main()
